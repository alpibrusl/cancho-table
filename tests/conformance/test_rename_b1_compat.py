"""G-COMPAT of slice B1 of docs/or-and-columns.md (`--rename`, `select a as b`): every call that is valid today means the same bytes.

* **the corpus**: the 166 runs of scripts/corpus.py (41 plans) on the benchmark and adversarial files give, as a listing of md5s, the md5 recorded for `main` `ba21e17` (A2 merged): `fccb01b66dd7518d74611219a6c5aa29`,
  and explained (CORPUS_EXPLAIN=1) `EXPLAIN_MD5` below. Skipped when the files are not generated here (CI generates only the benchmark file); the pull request quotes the run.
* **today's calls, byte for byte** (RENAME_B1_BASE names the directory of main's build): generated plans (query_gen, no rename), as flags and as queries, in json and csv and with threads, and
  --explain of them, run on both binaries: the same stdout, stderr and status. The one rule that says something new is `output.duplicate-column`, whose hint now points at --rename (docs/or-and-columns.md
  section 8.2), in the rule table (`introspect`): a csv or JSON-lines refusal is one sentence that carries no hint.
* the goldens of A0, A1 and A2 (test_or_a1_compat, test_not_a2_compat) are held by their own tests, which list the new accepted forms (`as`) in rename_b1_compat_changes.json.
"""
import hashlib
import json
import os
import pathlib
import random
import tempfile
import unittest

import query_gen
import procs as subprocess
from harness import ROOT, binary, run, run_argv

CORPUS_MD5 = "fccb01b66dd7518d74611219a6c5aa29"
EXPLAIN_MD5 = os.environ.get("RENAME_B1_EXPLAIN_MD5", "0c1ac7d875b01542d20b7d3fe9af2b28")
BASE = os.environ.get("RENAME_B1_BASE")
OLD_HINT = "name each column once: select it once, and each aggregate once"
CASES = int(os.environ.get("RENAME_B1_COMPAT", "400"))
FILES = [ROOT / "build" / "bench" / "data.csv", ROOT / "build" / "adv" / "f2.csv", ROOT / "build" / "adv" / "quoted.csv", ROOT / "build" / "adv" / "long.csv", ROOT / "build" / "adv" / "wide.csv",
         ROOT / "build" / "num" / "data.csv"]


def corpus(explain):
    env = dict(os.environ, TABLE=binary())
    if explain:
        env["CORPUS_EXPLAIN"] = "1"
    p = subprocess.run(["python3", str(ROOT / "scripts" / "corpus.py")], capture_output=True, env=env, timeout=3000)
    assert p.returncode == 0, p.stderr[:300]
    return p.stdout


class Corpus(unittest.TestCase):
    @unittest.skipUnless(all(f.exists() for f in FILES), "the benchmark, adversarial and numeric files are generated by scripts/bench.py, adversarial.py and bench_numbers.py")
    def test_the_corpus_is_main_s(self):
        out = corpus(False)
        self.assertEqual(len(out.splitlines()), 166)
        self.assertEqual(hashlib.md5(out).hexdigest(), CORPUS_MD5)

    @unittest.skipUnless(all(f.exists() for f in FILES), "the benchmark, adversarial and numeric files are generated by scripts/bench.py, adversarial.py and bench_numbers.py")
    def test_the_explain_of_the_corpus_is_main_s(self):
        out = corpus(True)
        self.assertEqual(len(out.splitlines()), 166)
        self.assertEqual(hashlib.md5(out).hexdigest(), EXPLAIN_MD5)


NEW_HINT = OLD_HINT + ", or rename one with --rename"


def norm(r, exe, d):
    """(status, stdout, stderr) with the paths of the binary and of the directory named, and the new hint of output.duplicate-column the old one (the one change of a refusal)."""
    fix = lambda b: b.replace(exe.encode(), b"{BIN}").replace(str(d).encode(), b"{DIR}").replace(NEW_HINT.encode(), OLD_HINT.encode())
    return r.status, fix(r.stdout), fix(r.stderr)


class Today(unittest.TestCase):
    @unittest.skipUnless(BASE, "RENAME_B1_BASE names the directory of main's build")
    def test_generated_calls_are_byte_identical_on_both_binaries(self):
        base = str(pathlib.Path(BASE) / "table")
        rnd = random.Random(7)
        ran = same = refusals = 0
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "f.csv")
            for case in range(CASES):
                names, kinds, rows = query_gen.make_table(rnd)
                query_gen.write_csv(path, names, rows)
                plan = query_gen.make_plan(rnd, names, kinds, rows, many=True)
                flags = query_gen.flag_form(plan)
                query = query_gen.query_form(rnd, plan, None)
                for argv in (flags, ["--query", query]):
                    for extra in ([], ["--format", "csv"], ["--format", "jsonl"], ["--explain"], ["--threads", "4", "--parallel-min-bytes", "0", "--chunk-bytes", "64"]):
                        old = run_argv([base, *argv, *extra, "f.csv"], cwd=d)
                        new = run(*argv, *extra, "f.csv", cwd=d)
                        a, b = norm(old, base, d), norm(new, binary(), d)
                        ran += 1
                        if old.status != 0:
                            refusals += 1
                        self.assertEqual(a, b, "case %d: %r %r" % (case, argv, extra))
                        same += 1
        self.assertEqual(ran, same)
        self.assertGreater(refusals, ran // 20)

    @unittest.skipUnless(BASE, "RENAME_B1_BASE names the directory of main's build")
    def test_the_duplicate_column_rule_changes_its_hint_and_nothing_else(self):
        # the hint of output.duplicate-column is in the rule table (introspect, docs/refusals.md): a csv or JSON-lines refusal is one sentence that carries no hint
        base = str(pathlib.Path(BASE) / "table")
        old = {r["rule"]: r for r in json.loads(subprocess.run([base, "introspect"], capture_output=True).stdout)["rules"]}
        new = {r["rule"]: r for r in json.loads(subprocess.run([binary(), "introspect"], capture_output=True).stdout)["rules"]}
        added = {"rename.syntax", "rename.unknown-target", "rename.ambiguous-target", "rename.repeated-target"}
        self.assertEqual(set(new) - set(old), added)
        self.assertEqual(set(old) - set(new), set())
        changed = {k for k in old if old[k] != new[k]}
        self.assertEqual(changed, {"output.duplicate-column"} | {k for k in changed if k != "output.duplicate-column" and "--rename" in new[k]["summary"]})
        self.assertIn(OLD_HINT, old["output.duplicate-column"]["summary"])
        self.assertIn(NEW_HINT, new["output.duplicate-column"]["summary"])
        self.assertEqual(new["output.duplicate-column"]["summary"].replace(NEW_HINT, OLD_HINT), old["output.duplicate-column"]["summary"])


if __name__ == "__main__":
    unittest.main()
